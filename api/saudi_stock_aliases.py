_UPPER_ALIAS_LOOKUP: Dict[str, str] = {
    **{k.upper(): v for k, v in _EXACT_ONLY_SAUDI_ALIASES.items()},
    **{k.upper(): v for k, v in SAUDI_STOCK_ALIASES.items()},
}
_NORMALIZED_LOOKUP: Dict[str, str] = {
    **{_normalize_arabic_text(k).upper(): v for k, v in _EXACT_ONLY_SAUDI_ALIASES.items()},
    **{_normalize_arabic_text(k).upper(): v for k, v in SAUDI_STOCK_ALIASES.items()},
}


def is_saudi_symbol(sym: str) -> bool:
    """Return True if `sym` is a Tadawul 4-digit ticker (optionally .SR/.SA/.TADAWUL) or known Saudi alias."""
    if not sym:
        return False
    s = sym.strip()
    if not s:
        return False
    if _SAUDI_CODE_RE.match(s):
        return True
    upper = s.upper()
    if upper in _UPPER_ALIAS_LOOKUP or s in SAUDI_STOCK_NAMES_AR:
        return True
    norm_upper = _normalize_arabic_text(s).upper()
    return norm_upper in _NORMALIZED_LOOKUP


def _extract_code_matches(text: str) -> List[tuple[int, int, str]]:
    matches: List[tuple[int, int, str]] = []
    for m in _SAUDI_CODE_IN_TEXT_RE.finditer(text):
        code = m.group(1)
        has_suffix = bool(m.group(2))
        if has_suffix or code in SAUDI_STOCK_NAMES_AR:
            matches.append((m.start(1), m.end(), code))
    return matches


def resolve_saudi_symbol(text: str) -> Optional[str]:
    """Resolve an Arabic/English Saudi company name or 4-digit Tadawul ticker to its 4-digit symbol."""
    if not text:
        return None
    clean_text = text.strip()
    if not clean_text:
        return None

    # 1. Exact / normalized full-string lookup
    upper = clean_text.upper()
    if upper in _UPPER_ALIAS_LOOKUP:
        return _UPPER_ALIAS_LOOKUP[upper]
    norm_upper = _normalize_arabic_text(clean_text).upper()
    if norm_upper in _NORMALIZED_LOOKUP:
        return _NORMALIZED_LOOKUP[norm_upper]

    # 2. Explicit 4-digit Saudi code (2222, 2222.SR, 2222.TADAWUL)
    code_matches = _extract_code_matches(clean_text)
    if code_matches:
        return code_matches[0][2]

    # 3. Arabic phrase word-boundary match (exact, then normalized)
    m = _ARABIC_EXACT_RE.search(clean_text)
    if m:
        return _ARABIC_PHRASE_MAP[m.group(1)]

    norm_text = _normalize_arabic_text(clean_text)
    if norm_text:
        m = _ARABIC_NORM_RE.search(norm_text)
        if m:
            return _NORMALIZED_ARABIC_PHRASE_MAP[m.group(1)]

    # 4. English alias word-boundary match
    m = _ENGLISH_PHRASES_RE.search(upper)
    if m:
        return _ENGLISH_PHRASE_MAP[m.group(1)]

    return None


def extract_all_saudi_symbols(text: str) -> List[str]:
    """Extract all distinct 4-digit Saudi stock symbols mentioned in `text`, preserving order."""
    if not text:
        return []
    clean_text = text.strip()
    if not clean_text:
        return []

    found: List[tuple[int, str]] = []
    matched_regions: List[tuple[int, int]] = []

    def _overlaps(start: int, end: int) -> bool:
        return any(s < end and start < e for s, e in matched_regions)

    # 1. Explicit 4-digit Saudi codes
    for start, end, code in _extract_code_matches(clean_text):
        if not _overlaps(start, end):
            matched_regions.append((start, end))
            found.append((start, code))

    # 2. Exact Arabic phrases (word-boundary, optional single proclitic)
    for m in _ARABIC_EXACT_RE.finditer(clean_text):
        start, end = m.start(), m.end()
        if not _overlaps(start, end):
            matched_regions.append((start, end))
            found.append((start, _ARABIC_PHRASE_MAP[m.group(1)]))

    # 3. Normalized Arabic phrases (mapped back to clean_text coordinates)
    norm_text, orig_indices = _normalize_arabic_with_map(clean_text)
    if norm_text:
        for m in _ARABIC_NORM_RE.finditer(norm_text):
            orig_start = orig_indices[m.start()]
            orig_end = orig_indices[m.end() - 1] + 1
            if not _overlaps(orig_start, orig_end):
                matched_regions.append((orig_start, orig_end))
                found.append((orig_start, _NORMALIZED_ARABIC_PHRASE_MAP[m.group(1)]))

    # 4. English aliases (word-boundary)
    upper = clean_text.upper()
    for m in _ENGLISH_PHRASES_RE.finditer(upper):
        start, end = m.start(), m.end()
        if not _overlaps(start, end):
            matched_regions.append((start, end))
            found.append((start, _ENGLISH_PHRASE_MAP[m.group(1)]))

    found.sort(key=lambda item: item[0])
    deduped: List[str] = []
    for _, sym in found:
        if sym not in deduped:
            deduped.append(sym)
    return deduped
