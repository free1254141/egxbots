def _build_aliases() -> Dict[str, str]:
    aliases: Dict[str, str] = {}
    for sym, name_ar in SAUDI_STOCK_NAMES_AR.items():
        aliases[sym] = sym
        aliases[f"{sym}.SR"] = sym
        aliases[f"{sym}.SA"] = sym
        aliases[f"{sym}.TADAWUL"] = sym
        aliases[name_ar] = sym
        # Also strip parenthetical suffix if present for natural matching
        if "(" in name_ar:
            base = name_ar.split("(", 1)[0].strip()
            if len(base) >= 3:
                aliases.setdefault(base, sym)
            inner = name_ar.split("(", 1)[1].rstrip(")").strip()
            if len(inner) >= 2:
                aliases.setdefault(inner, sym)
    for k, v in _EXTRA_SAUDI_ALIASES.items():
        aliases[k] = v
    return aliases


