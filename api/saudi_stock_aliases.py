_ARABIC_DIACRITICS_RE = re.compile(r"[\u064B-\u065F\u0670\u0640]")
_SAUDI_CODE_RE = re.compile(r"^\d{4}(\.(SR|SA|TADAWUL))?$", re.IGNORECASE)
_SAUDI_CODE_IN_TEXT_RE = re.compile(
    r"(?:^|(?<=[\s#($,:،؛/]))(\d{4})(?:\.(SR|SA|TADAWUL))?(?=$|[\s.,!?؟…)/:،؛])",
    re.IGNORECASE,
)
_BOUNDARY_CHARS = r"\s#()$,.:;!?؟…،؛\"'«»/+\-\[\]"
_ARABIC_BOUNDARY_LEFT = rf"(?:^|(?<=[{_BOUNDARY_CHARS}]))"
_ARABIC_BOUNDARY_RIGHT = rf"(?=$|[{_BOUNDARY_CHARS}])"


def _normalize_arabic_text(text: str) -> str:
    if not text:
        return ""
    s = _ARABIC_DIACRITICS_RE.sub("", text)
    s = (
        s.replace("أ", "ا")
        .replace("إ", "ا")
        .replace("آ", "ا")
        .replace("ة", "ه")
        .replace("ى", "ي")
        .replace("ؤ", "و")
        .replace("ئ", "ي")
    )
    return " ".join(s.split())


def _normalize_arabic_with_map(text: str) -> tuple[str, List[int]]:
    """Normalize Arabic text while keeping a char-index mapping back to `text`."""
    norm_chars: List[str] = []
    orig_indices: List[int] = []
    prev_space = True
    char_map = {
        "أ": "ا",
        "إ": "ا",
        "آ": "ا",
        "ة": "ه",
        "ى": "ي",
        "ؤ": "و",
        "ئ": "ي",
    }
    for idx, ch in enumerate(text):
        if _ARABIC_DIACRITICS_RE.match(ch):
            continue
        if ch.isspace():
            if not prev_space:
                norm_chars.append(" ")
                orig_indices.append(idx)
                prev_space = True
            continue
        norm_chars.append(char_map.get(ch, ch))
        orig_indices.append(idx)
        prev_space = False
    if norm_chars and norm_chars[-1] == " ":
        norm_chars.pop()
        orig_indices.pop()
    return "".join(norm_chars), orig_indices


