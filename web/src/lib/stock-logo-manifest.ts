export function hasLocalStockLogo(symbol: string): boolean {
  return LOCAL_LOGO_SYMBOLS.has((symbol || "").trim().toUpperCase().split(".")[0]);
}

export function getRemoteStockLogoUrl(symbol: string): string | null {
  const key = (symbol || "").trim().toUpperCase().split(".")[0];
  const slug = REMOTE_LOGO_SLUGS[key];
  if (!slug) return null;
  if (slug.startsWith("http://") || slug.startsWith("https://")) return slug;
  return `${TV_LOGO_CDN}${slug}.svg`;
}
